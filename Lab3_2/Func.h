
#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>
#include <math.h>
#include <time.h>



/**
 * @brief Очищає буфер стандартного введення (stdin).
 *
 * Зчитує всі залишкові символи з буфера до символу нового рядка ('\n') або EOF.
 * Використовується для запобігання зацикленню при некоректному вводі через scanf.
 *
 * @return void (нічого не повертає)
 */
void clear_input_buffer(void);

/**
 * @brief Обчислює значення вихідної нелінійної функції f(x) = x^3 - x - 4.
 *
 * @param x Точка, у якій обчислюється значення функції.
 * @return double Значення функції f(x) у точці x.
 */
double f(double x);

/**
 * @brief Обчислює значення першої похідної f'(x) = 3x^2 - 1.
 *
 * Використовується для аналізу монотонності та перевірки умов збіжності.
 *
 * @param x Точка, у якій обчислюється похідна.
 * @return double Значення похідної f'(x) у точці x.
 */
double df(double x);

/**
 * @brief Діалогова функція обробки події перевищення ліміту ітерацій.
 *
 * Запитує у користувача подальшу дію при досягненні max_iter.
 *
 * @param current_iter Поточний номер ітерації.
 * @param current_x Поточне наближення кореня.
 * @param current_f Значення функції у поточному наближенні f(current_x).
 *
 * @return int Код обраної дії:
 *         - 1: Продовжити обчислення ще на max_iter ітерацій.
 *         - 2: Виконати програму до кінця (поки не досягнемо eps).
 *         - 0: Перервати обчислення та повернути поточний проміжний результат.
 */
int handle_max_iter(int current_iter, double current_x, double current_f);

/**
 * @brief Розв'язує рівняння f(x) = 0 методом половинного ділення (дихотомії).
 *
 * @param a Ліва межа початкового інтервалу.
 * @param b Права межа початкового інтервалу.
 * @param eps Задана точність обчислень (критерій зупинки).
 * @param max_iter Максимальна кількість ітерацій до виклику діалогу продовження.
 * @param debug Прапорець режиму налагодження (1 — виводити кожну ітерацію, 0 — ні).
 *
 * @return void (результати, кількість ітерацій та час виконання виводяться в консоль)
 */
void solve_bisection(double a, double b, double eps, int max_iter, int debug);

/**
 * @brief Розв'язує рівняння f(x) = 0 методом хорд.
 *
 * @param a Ліва межа початкового інтервалу.
 * @param b Права межа початкового інтервалу.
 * @param eps Задана точність обчислень (критерій зупинки).
 * @param max_iter Максимальна кількість ітерацій до виклику діалогу продовження.
 * @param debug Прапорець режиму налагодження (1 — виводити кожну ітерацію, 0 — ні).
 *
 * @return void (результати, кількість ітерацій та час виконання виводяться в консоль)
 */
void solve_chord(double a, double b, double eps, int max_iter, int debug);
